import {cpSync,mkdirSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join,dirname} from 'node:path';
import {buildDossier} from './vendor/makefun-game.ts';
const root=dirname(fileURLToPath(import.meta.url));
const output=process.env.MAKEFUN_OUTPUT_DIR||'/output';
mkdirSync(output,{recursive:true});
for(const name of ['game','screenshots'])cpSync(join(root,name),join(output,name),{recursive:true});
const dossier=buildDossier(output,{text_max_bytes:163840,screenshots:{max:4,max_bytes:262144},game_max_files:993,game_max_bytes:50331648,game_path_max_bytes:1000});
writeFileSync(join(output,'dossier.json'),dossier);
console.log(`Tradewinds built in ${output} · ${dossier.byteLength} dossier bytes`);
if(dossier.byteLength>1572864)console.warn('Dossier exceeds 1.5 MiB');
