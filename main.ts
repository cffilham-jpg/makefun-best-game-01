import { cpSync, mkdirSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, join } from 'node:path';
import { buildDossier } from './vendor/makefun-game.ts';
const base = fileURLToPath(new URL('.', import.meta.url));
const destination = resolve(process.env.MAKEFUN_OUTPUT_DIR || '/output');
mkdirSync(destination, {recursive:true});
for (const folder of ['game','screenshots']) cpSync(join(base,folder),join(destination,folder),{recursive:true});
const dossier = buildDossier(destination,{text_max_bytes:163840,screenshots:{max:4,max_bytes:262144},game_max_files:993,game_max_bytes:50331648,game_path_max_bytes:1000});
writeFileSync(join(destination,'dossier.json'),dossier);
console.log(`Emberward built in ${destination}`);
console.log(`Dossier: ${Buffer.byteLength(dossier)} bytes`);
const gameFiles = readdirSync(join(base,'game'),{recursive:true,withFileTypes:true}).filter(entry=>entry.isFile()).length;
console.log(`Game files copied: ${gameFiles}`);
if (Buffer.byteLength(dossier) > 1572864) console.warn('Warning: dossier exceeds the 1.5 MiB cap (1572864 bytes).');
